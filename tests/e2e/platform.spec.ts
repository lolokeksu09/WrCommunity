test('уведомления и модерация: настройки сохраняются, жалоба и решение меняют доступ',async({browser})=>{
  const owner=await account(),reporter=await account(),moderator=await account({moderator:true});
  const post=await api(owner.context,'/posts','POST',{body:'Материал для рассмотрения жалобы',state:'published'});
  const a=await browserPerson(browser,reporter),m=await browserPerson(browser,moderator);
  await a.page.goto('/notifications/settings');
  await a.page.getByLabel('Отметки «Нравится»').uncheck();
  await a.page.getByRole('button',{name:'Сохранить настройки'}).click();
  await expect(a.page.getByRole('status')).toContainText('Настройки уведомлений сохранены');
  await a.page.reload();
  await expect(a.page.getByLabel('Отметки «Нравится»')).not.toBeChecked();
  await a.page.goto('/report?type=post&id='+post.id);
  await a.page.getByLabel('Причина жалобы').fill('Проверка фактического процесса модерации');
  await a.page.getByRole('button',{name:'Отправить жалобу'}).click();
  await expect(a.page.getByRole('heading',{name:'Жалоба отправлена'})).toBeVisible();
  const reports=await api(reporter.context,'/me/reports');
  const report=reports.items.find((r:any)=>r.target_id===post.id);expect(report).toBeTruthy();
  await m.page.goto('/platform/moderation/reports/'+report.id);
  await expect(m.page.locator('.evidence')).toContainText('Материал для рассмотрения жалобы');
  await m.page.getByLabel('Обоснование решения').fill('Материал скрыт после проверки жалобы');
  await m.page.getByRole('button',{name:'Скрыть материал',exact:true}).click();
  await expect(m.page.getByRole('status')).toContainText('Решение сохранено');
  await a.page.goto('/posts/'+post.id);
  await expect(a.page.getByRole('heading',{name:'Страница недоступна'})).toBeVisible();
  await m.page.goto('/platform/moderation/audit');
  await expect(m.page.getByText('Материал скрыт после проверки жалобы',{exact:true})).toBeVisible();
  expect([...a.errors,...m.errors]).toEqual([]);
  await Promise.all([a.context.close(),m.context.close(),owner.context.dispose(),reporter.context.dispose(),moderator.context.dispose()]);
});

