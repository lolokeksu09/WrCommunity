test('регистрация, подтверждение письма, приватность и публикация сохраняются после обновления',async({page})=>{
  const key=randomUUID().replaceAll('-','').slice(0,15),email=`ui-${key}@example.com`;
  await page.goto('/signup');
  await page.getByLabel('Электронная почта').fill(email);
  await page.getByLabel('Как тебя зовут').fill('Новый игрок '+key);
  await page.getByLabel('Уникальный ник').fill('ui_'+key);
  await page.getByLabel('Пароль',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Создать аккаунт',exact:true}).click();
  await expect(page).toHaveURL(/account\/verify-email/);
  await page.getByLabel('Код из письма').fill(await verificationToken(email));
  await page.getByRole('button',{name:'Подтвердить почту',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Почта подтверждена'})).toBeVisible();
  await page.goto('/me/privacy');
  await page.getByRole('radio',{name:/Публичный/}).check();
  await page.getByLabel('Я понимаю последствия изменения видимости профиля.').check();
  await page.getByRole('button',{name:'Сохранить изменения'}).click();
  await expect(page.getByText('Публичный профиль',{exact:true})).toBeVisible();
  await page.goto('/posts/new');
  await page.getByLabel('Текст публикации').fill('Первый настоящий пост '+key);
  const image=await sharp({create:{width:40,height:40,channels:3,background:'#7185a3'}}).png().toBuffer();
  await page.locator('.upload-button input').setInputFiles({name:'test-image.png',mimeType:'image/png',buffer:image});
  await expect(page.locator('.upload-grid img')).toBeVisible();
  await page.getByRole('button',{name:'Опубликовать',exact:true}).click();
  await expect(page).toHaveURL(/\/posts\/[a-f0-9-]+$/);
  await page.getByLabel('Твой комментарий').fill('Комментарий после регистрации');
  await page.getByRole('button',{name:'Отправить',exact:true}).click();
  await expect(page.locator('.comment').getByText('Комментарий после регистрации',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.locator('.post-body')).toContainText('Первый настоящий пост '+key);
  await expect(page.locator('.post-images img')).toBeVisible();
  await expect(page.locator('.comment')).toContainText('Комментарий после регистрации');
  await noOverflow(page);
});

test('подписка, лайк, закладка, дерево ответов и контекстная блокировка скрытого автора',async({browser})=>{
  const owner=await account(),reader=await account(),hidden=await account({hidden:true});
  const post=await api(owner.context,'/posts','POST',{body:'Пост для обсуждения '+owner.handle,state:'published'});
  const hiddenComment=await api(hidden.context,'/posts/'+post.id+'/comments','POST',{body:'Комментарий скрытого профиля'});
  const ui=await browserPerson(browser,reader);
  await ui.page.goto('/users/'+owner.id);
  await ui.page.getByRole('button',{name:'Подписаться',exact:true}).click();
  await expect(ui.page.getByRole('button',{name:'Вы подписаны'})).toBeVisible();
  await ui.page.goto('/posts/'+post.id);
  await ui.page.getByRole('button',{name:'Нравится',exact:true}).click();
  await expect(ui.page.getByRole('button',{name:'Убрать отметку нравится'})).toHaveAttribute('aria-pressed','true');
  await ui.page.getByRole('button',{name:'Сохранить в закладки'}).click();
  await ui.page.getByLabel('Твой комментарий').fill('Корневой ответ');
  await ui.page.getByRole('button',{name:'Отправить',exact:true}).click();
  const root=ui.page.locator('.comment').filter({has:ui.page.getByText('Корневой ответ',{exact:true})});
  await root.getByRole('button',{name:'Ответить',exact:true}).click();
  await ui.page.getByLabel('Ответить',{exact:true}).fill('Вложенный ответ');
  await ui.page.getByRole('button',{name:'Отправить',exact:true}).click();
  await expect(ui.page.locator('.comment-children')).toContainText('Вложенный ответ');
  await ui.page.reload();
  await expect(ui.page.getByRole('button',{name:'Убрать закладку'})).toHaveAttribute('aria-pressed','true');
  const hiddenNode=ui.page.locator('.comment').filter({hasText:'Комментарий скрытого профиля'});
  await expect(hiddenNode.locator('.author')).not.toHaveAttribute('href');
  await hiddenNode.getByRole('button',{name:'Заблокировать автора'}).click();
  await hiddenNode.getByRole('button',{name:'Подтвердить',exact:true}).click();
  await expect(ui.page.getByText('Комментарий скрытого профиля',{exact:true})).toHaveCount(0);
  expect((await api(reader.context,'/blocks')).items.some((p:any)=>p.id===hidden.id)).toBeTruthy();
  expect(ui.errors).toEqual([]);
  await ui.context.close();
  await Promise.all([owner.context.dispose(),reader.context.dispose(),hidden.context.dispose()]);
});

