import {test,expect} from '@playwright/test';
import {account,api,browserPerson,noOverflow} from './helpers.js';

test('первые шаги и собственные фильтры не раскрывают скрытый профиль',async({browser},testInfo)=>{
 test.setTimeout(90000);
 const viewer=await account({hidden:true}),other=await account({hidden:true}),target=await account();
 const ui=await browserPerson(browser,viewer);
 try{
  await ui.page.goto('/me');
  const steps=ui.page.getByRole('region',{name:'Первые шаги'});
  await expect(steps).toContainText('Готово: 1 из 2');
  await expect(steps).toContainText('Почта подтверждена');
  await steps.getByRole('link',{name:'Заполнить игровую карточку'}).click();
  await ui.page.getByLabel('Сервер',{exact:true}).fill('EU');
  await ui.page.getByRole('group',{name:'Роли',exact:true}).getByRole('checkbox',{name:'Мид',exact:true}).check();
  await ui.page.getByRole('button',{name:'Сохранить изменения',exact:true}).click();
  await expect(steps).toContainText('Готово: 2 из 2');
  const own=await api(viewer.context,'/me/profile');
  await api(viewer.context,'/me/profile','PATCH',{version:own.version,game:{roles:{value:['Мид','support','Тактик','ДлиннаяРоль'.repeat(5)],public:false}}});
  const candidate=await api(target.context,'/me/profile');
  await api(target.context,'/me/profile','PATCH',{version:candidate.version,game:{server:{value:'EU',public:true},roles:{value:['support'],public:true}}});
  await ui.page.reload();
  await noOverflow(ui.page);
  await ui.page.screenshot({path:testInfo.outputPath('profile-steps.png'),fullPage:true});
  await steps.getByRole('button',{name:'Свернуть первые шаги'}).click();
  await expect(steps.getByRole('link',{name:'Найти игроков',exact:true})).toHaveCount(0);
  await ui.page.reload();
  await expect(steps.getByRole('button',{name:'Показать первые шаги'})).toHaveAttribute('aria-expanded','false');
  await steps.getByRole('button',{name:'Показать первые шаги'}).click();
  await steps.getByRole('link',{name:'Найти игроков',exact:true}).click();
  await ui.page.goto('/discover?mode=recommended&q='+target.handle);
  const preset=ui.page.getByRole('region',{name:'Свои настройки поиска'});
  await expect(preset).toContainText('EU');
  await expect(preset.getByRole('option',{name:'ДлиннаяРоль'.repeat(5),exact:true})).toHaveCount(0);
  await preset.getByLabel('Роль из моей карточки').selectOption('Тактик');
  await preset.getByRole('button',{name:'Использовать мои настройки'}).click();
  await expect.poll(()=>new URL(ui.page.url()).searchParams.get('role')).toBe('Тактик');
  await expect(preset.getByLabel('Роль из моей карточки')).toHaveValue('Тактик');
  await preset.getByLabel('Роль из моей карточки').selectOption('support');
  await preset.getByRole('button',{name:'Использовать мои настройки'}).click();
  await expect(ui.page.locator('.person')).toHaveCount(1);
  const applied=new URL(ui.page.url()).searchParams;
  expect(applied.get('q')).toBe(target.handle);expect(applied.get('mode')).toBe('recommended');
  expect(applied.get('server')).toBe('EU');expect(applied.get('role')).toBe('support');expect(applied.has('cursor')).toBe(false);
  await expect(ui.page.locator('.person')).toContainText('Совпадает игровая роль');
  await noOverflow(ui.page);
  await ui.page.screenshot({path:testInfo.outputPath('preferred-search.png'),fullPage:true});
  await ui.page.getByRole('link',{name:'Сбросить фильтры'}).click();
  await expect(ui.page).toHaveURL(/\/discover\?mode=recommended$/);
  await ui.page.goto('/discover/lfg');
  await ui.page.getByRole('region',{name:'Свои настройки поиска'}).getByLabel('Роль из моей карточки').selectOption('support');
  await ui.page.getByRole('button',{name:'Использовать мои настройки'}).click();
  await expect.poll(()=>new URL(ui.page.url()).searchParams.get('role')).toBe('support');
  const saved=await api(viewer.context,'/me/profile');
  expect(saved.visibility).toBe('hidden');expect(saved.game.server.public).toBe(false);expect(saved.game.roles.public).toBe(false);
  await ui.context.clearCookies();await ui.context.addCookies((await other.context.storageState()).cookies);
  await ui.page.goto('/me');
  await expect(steps.getByRole('button',{name:'Свернуть первые шаги'})).toBeVisible();
  await expect(steps).toContainText('Готово: 1 из 2');
  await ui.page.addInitScript(()=>{Storage.prototype.setItem=function(){throw new DOMException('Storage unavailable','SecurityError');};});
  await ui.page.reload();
  await steps.getByRole('button',{name:'Свернуть первые шаги'}).click();
  await steps.getByRole('button',{name:'Показать первые шаги'}).click();
  await expect(steps.getByRole('link',{name:'Заполнить игровую карточку'})).toBeVisible();
  await ui.context.clearCookies();
  const guestReads:string[]=[];ui.page.on('request',r=>{if(r.url().includes('/api/v1/me/profile'))guestReads.push(r.url());});
  await ui.page.goto('/discover');
  await expect(ui.page.getByRole('region',{name:'Свои настройки поиска'})).toHaveCount(0);
  expect(guestReads).toEqual([]);expect(ui.errors).toEqual([]);
 }finally{await ui.context.close();await viewer.context.dispose();await other.context.dispose();await target.context.dispose();}
});
